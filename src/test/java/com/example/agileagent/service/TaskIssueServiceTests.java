package com.example.agileagent.service;

import com.example.agileagent.agent.TaskTools;
import com.example.agileagent.config.ProjectScope;
import com.example.agileagent.dto.CreateTaskRequest;
import com.example.agileagent.dto.TaskIssueDTO;
import com.example.agileagent.dto.UpdateTaskRequest;
import com.example.agileagent.entity.TaskIssueEntity;
import com.example.agileagent.mapper.TaskIssueMapper;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

import java.util.Arrays;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
@Transactional
class TaskIssueServiceTests {
    @Autowired TaskIssueService tasks;
    @Autowired JdbcTemplate jdbc;

    @BeforeEach
    void setup() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS app_user (id BIGINT PRIMARY KEY, username VARCHAR(100), display_name VARCHAR(100), api_key_hash VARCHAR(64), created_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS agile_project (id BIGINT PRIMARY KEY, name VARCHAR(200), description VARCHAR(1000), owner_id BIGINT, created_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS project_member (id BIGINT PRIMARY KEY, project_id BIGINT, user_id BIGINT, role VARCHAR(20), created_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS task_issue (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL, task_log_id BIGINT, title VARCHAR(255), assignee_name VARCHAR(50), description CLOB, priority VARCHAR(20), deadline DATE, is_completed INTEGER)");
        jdbc.update("INSERT INTO agile_project (id,name,owner_id) VALUES (10,'A',1),(20,'B',1)");
        jdbc.update("INSERT INTO project_member (id,project_id,user_id,role) VALUES (1,10,2,'MEMBER'),(2,10,3,'VIEWER'),(3,20,2,'MEMBER')");
        jdbc.update("INSERT INTO task_issue (id,project_id,title,assignee_name,priority,is_completed) VALUES (101,10,'A task','Alice','HIGH',0),(102,10,'done','Alice','LOW',1),(201,20,'B task','Alice','HIGH',0)");
    }

    @AfterEach
    void clear() { ProjectScope.clear(); }

    @Test
    void memberCanCreateAndUpdate() {
        ProjectScope.runAs(2L, 10L, () -> {
            TaskIssueEntity created = tasks.createTask(10L, new CreateTaskRequest("new", "Bob", "desc", "LOW", "2026-12-01"));
            TaskIssueEntity updated = tasks.updateTask(10L, created.getId(), new UpdateTaskRequest("changed", "Bob", null, "HIGH", null));
            assertEquals("changed", updated.getTitle());
            assertEquals("HIGH", tasks.getTask(10L, created.getId()).getPriority());
            assertNull(tasks.getTask(10L, created.getId()).getDeadline());
        });
    }

    @Test
    void viewerReadsButCannotWriteAndNonMemberCannotRead() {
        ProjectScope.runAs(3L, 10L, () -> {
            assertEquals(2, tasks.listTasks(10L, 1, 20, null, null, null).total());
            assertThrows(SecurityException.class, () -> tasks.createTask(10L, valid()));
            assertThrows(SecurityException.class, () -> tasks.updateTask(10L, 101L, new UpdateTaskRequest("x", null, null, "LOW", null)));
            assertThrows(SecurityException.class, () -> tasks.updatePriority(10L, 101L, "LOW"));
            assertThrows(SecurityException.class, () -> tasks.setCompleted(10L, 101L, true));
            assertThrows(SecurityException.class, () -> tasks.deleteTask(10L, 101L));
        });
        ProjectScope.runAs(9L, 10L, () -> assertThrows(SecurityException.class,
                () -> tasks.listTasks(10L, 1, 20, null, null, null)));
    }

    @Test
    void taskIdAndProjectAreBothEnforced() {
        ProjectScope.runAs(2L, 10L, () -> {
            assertThrows(TaskNotFoundException.class, () -> tasks.updatePriority(10L, 201L, "LOW"));
            assertThrows(TaskNotFoundException.class, () -> tasks.deleteTask(10L, 201L));
            assertThrows(SecurityException.class, () -> tasks.getTask(20L, 201L));
        });
        assertEquals("B task", jdbc.queryForObject("SELECT title FROM task_issue WHERE id=201", String.class));
    }

    @Test
    void validationAndPageFiltersApplyToCurrentProject() {
        ProjectScope.runAs(2L, 10L, () -> {
            assertThrows(IllegalArgumentException.class, () -> tasks.createTask(10L, new CreateTaskRequest(" ", null, null, "HIGH", null)));
            assertThrows(IllegalArgumentException.class, () -> tasks.createTask(10L, new CreateTaskRequest("x", null, null, "URGENT", null)));
            assertThrows(IllegalArgumentException.class, () -> tasks.createTask(10L, new CreateTaskRequest("x", null, null, "HIGH", "2026-02-30")));
            assertThrows(IllegalArgumentException.class, () -> tasks.listTasks(10L, 1, 101, null, null, null));
            var result = tasks.listTasks(10L, 1, 1, "Alice", "HIGH", false);
            assertEquals(1, result.total());
            assertEquals(101L, result.records().get(0).getId());
            assertTrue(tasks.listTasks(10L, 2, 1, "Alice", "HIGH", false).records().isEmpty());
        });
    }

    @Test
    void aiBatchValidatesAllBeforeSaving() {
        TaskIssueDTO valid = new TaskIssueDTO(); valid.setTitle("valid"); valid.setPriority("HIGH");
        TaskIssueDTO invalid = new TaskIssueDTO(); invalid.setTitle("invalid"); invalid.setPriority("BAD");
        ProjectScope.runAs(2L, 10L, () -> assertThrows(IllegalArgumentException.class,
                () -> tasks.saveIssuesFromAi(10L, List.of(valid, invalid))));
        assertEquals(2, jdbc.queryForObject("SELECT COUNT(*) FROM task_issue WHERE project_id=10", Integer.class));
    }

    @Test
    void toolDoesNotDependOnMapper() {
        assertTrue(Arrays.stream(TaskTools.class.getDeclaredFields())
                .noneMatch(field -> TaskIssueMapper.class.isAssignableFrom(field.getType())));
    }

    private CreateTaskRequest valid() { return new CreateTaskRequest("new", null, null, "MEDIUM", null); }
}
