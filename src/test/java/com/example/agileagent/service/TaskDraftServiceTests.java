        jdbc.execute("CREATE TABLE IF NOT EXISTS task_issue (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL, task_log_id BIGINT, title VARCHAR(255), assignee_name VARCHAR(50), description CLOB, priority VARCHAR(20), deadline DATE, is_completed INTEGER)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS task_draft (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL, created_by BIGINT NOT NULL, source_type VARCHAR(30), source_ref VARCHAR(500), source_content_hash CHAR(64), status VARCHAR(20), idempotency_key VARCHAR(100), failure_reason VARCHAR(1000), submitted_task_ids CLOB, created_at TIMESTAMP, updated_at TIMESTAMP, confirmed_at TIMESTAMP, submitted_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS task_draft_item (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, draft_id BIGINT NOT NULL, title VARCHAR(255), assignee_name VARCHAR(50), description CLOB, priority VARCHAR(20), deadline DATE, sort_order INTEGER, created_at TIMESTAMP, updated_at TIMESTAMP)");
