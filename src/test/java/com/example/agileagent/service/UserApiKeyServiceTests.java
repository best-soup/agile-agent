package com.example.agileagent.service;

import com.example.agileagent.config.ProjectScope;
import com.example.agileagent.entity.ApiKeyEntity;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;

import java.time.LocalDateTime;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest(properties = "spring.datasource.url=jdbc:h2:mem:api_key_test;MODE=MySQL;DB_CLOSE_DELAY=-1")
class UserApiKeyServiceTests {
    @Autowired UserApiKeyService keys;
    @Autowired UserAuthService auth;
    @Autowired JdbcTemplate jdbc;
    @Autowired ObjectMapper objectMapper;

    @BeforeEach
    void setup() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS app_user (id BIGINT PRIMARY KEY, username VARCHAR(100), display_name VARCHAR(100), api_key_hash VARCHAR(64), created_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS api_key (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL, name VARCHAR(100), key_prefix VARCHAR(20), key_hash VARCHAR(64) UNIQUE, status VARCHAR(20), expires_at TIMESTAMP, revoked_at TIMESTAMP, last_used_at TIMESTAMP, created_at TIMESTAMP)");
        jdbc.update("DELETE FROM api_key");
        jdbc.update("DELETE FROM app_user");
        jdbc.update("INSERT INTO app_user (id,username,display_name,created_at) VALUES (1,'alice','Alice',CURRENT_TIMESTAMP),(2,'bob','Bob',CURRENT_TIMESTAMP)");
    }

    @AfterEach
    void clear() { ProjectScope.clear(); }

    @Test
    void createAndAuthenticateKeyThenWrongKeyFails() {
        ProjectScope.authenticate(1L);
        var created = keys.createForCurrentUser("laptop", null);
        assertNotNull(created.apiKey());
        assertTrue(created.apiKey().length() >= 40);
        assertEquals(UserApiKeyService.ACTIVE, created.key().status());
        assertEquals(1L, auth.requireUser(created.apiKey()).getId());
        assertThrows(SecurityException.class, () -> auth.requireUser("agk_invalid"));
        assertNotEquals(created.apiKey(), jdbc.queryForObject("SELECT key_hash FROM api_key WHERE id=?", String.class, created.key().id()));
    }

    @Test
    void revokeImmediatelyStopsAuthenticationAndCannotRotate() {
        ProjectScope.authenticate(1L);
        var created = keys.createForCurrentUser("primary", null);
        keys.revokeForCurrentUser(created.key().id());
        assertThrows(SecurityException.class, () -> auth.requireUser(created.apiKey()));
        assertThrows(ApiKeyStateException.class, () -> keys.rotateForCurrentUser(created.key().id(), null, null));
    }

    @Test
    void expiryStopsAuthenticationAndCannotRotateOrRevoke() {
        ProjectScope.authenticate(1L);
        var created = keys.createForCurrentUser("temporary", LocalDateTime.now().plusSeconds(1).toString());
        ApiKeyEntity key = jdbc.queryForObject("SELECT * FROM api_key WHERE id=?", (rs, rowNum) -> ApiKeyEntity.builder()
                .id(rs.getLong("id")).userId(rs.getLong("user_id")).name(rs.getString("name"))
                .keyPrefix(rs.getString("key_prefix")).keyHash(rs.getString("key_hash"))
                .status(rs.getString("status")).expiresAt(rs.getTimestamp("expires_at").toLocalDateTime()).build(), created.key().id());
        jdbc.update("UPDATE api_key SET expires_at=? WHERE id=?", LocalDateTime.now().minusSeconds(1), key.getId());
        assertThrows(SecurityException.class, () -> auth.requireUser(created.apiKey()));
        assertEquals(UserApiKeyService.EXPIRED, jdbc.queryForObject("SELECT status FROM api_key WHERE id=?", String.class, key.getId()));
        assertThrows(ApiKeyStateException.class, () -> keys.rotateForCurrentUser(key.getId(), null, null));
        assertThrows(ApiKeyStateException.class, () -> keys.revokeForCurrentUser(key.getId()));
    }

    @Test
    void userCanOwnMultipleKeysAndRotationReturnsNewKey() {
        ProjectScope.authenticate(1L);
        var first = keys.createForCurrentUser("one", null);
        var second = keys.createForCurrentUser("two", null);
        assertEquals(2, keys.listForCurrentUser().size());
        var rotated = keys.rotateForCurrentUser(first.key().id(), "rotated", null);
        assertNotEquals(first.apiKey(), rotated.apiKey());
        assertEquals(UserApiKeyService.REVOKED, jdbc.queryForObject("SELECT status FROM api_key WHERE id=?", String.class, first.key().id()));
        assertEquals(1L, auth.requireUser(rotated.apiKey()).getId());
        assertEquals(1L, auth.requireUser(second.apiKey()).getId());
    }

    @Test
    void userCannotManageAnotherUsersKeyAndListDoesNotExposeHashOrPlainKey() throws Exception {
        ProjectScope.authenticate(1L);
        var created = keys.createForCurrentUser("private", null);
        ProjectScope.authenticate(2L);
        assertThrows(ApiKeyNotFoundException.class, () -> keys.revokeForCurrentUser(created.key().id()));
        assertThrows(ApiKeyNotFoundException.class, () -> keys.rotateForCurrentUser(created.key().id(), null, null));
        assertTrue(keys.listForCurrentUser().isEmpty());
        String json = objectMapper.writeValueAsString(keys.listForCurrentUser());
        assertFalse(json.contains(created.apiKey()));
        assertFalse(json.contains(UserApiKeyService.sha256(created.apiKey())));
    }

    @Test
    void invalidNameAndExpiryAreRejected() {
        ProjectScope.authenticate(1L);
        assertThrows(IllegalArgumentException.class, () -> keys.createForCurrentUser("x".repeat(101), null));
        assertThrows(IllegalArgumentException.class, () -> keys.createForCurrentUser("x", "not-a-date"));
        assertThrows(IllegalArgumentException.class, () -> keys.createForCurrentUser("x", LocalDateTime.now().minusMinutes(1).toString()));
    }
}
