@SpringBootTest(properties = "spring.datasource.url=jdbc:h2:mem:meeting_test;MODE=MySQL;DB_CLOSE_DELAY=-1")
class MeetingRecordServiceTests {
    MeetingRecordService meetings;
    @Autowired JdbcTemplate jdbc;
    @MockBean RagService rag;
    AgileMasterAgent agent;
    @Autowired MeetingRecordMapper records;
    @Autowired RagDocumentMapper ragDocuments;
    @Autowired AuditLogMapper audit;
    @Autowired ProjectAccessService access;
    @Autowired MeetingSourceImporter importer;
    @Autowired TaskDraftService drafts;
    @Autowired PlatformTransactionManager transactions;

    @BeforeEach
    void setup() {
        agent = mock(AgileMasterAgent.class);
        meetings = new MeetingRecordService(records, audit, ragDocuments, access, importer, rag, agent, drafts, transactions);
        jdbc.execute("CREATE TABLE IF NOT EXISTS agile_project (id BIGINT PRIMARY KEY, name VARCHAR(200), description VARCHAR(1000), owner_id BIGINT, created_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS project_member (id BIGINT PRIMARY KEY, project_id BIGINT, user_id BIGINT, role VARCHAR(20), created_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS meeting_record (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT, source_type VARCHAR(30), source_id VARCHAR(255), identity_hash CHAR(64), title VARCHAR(255), content CLOB, content_hash CHAR(64), source_url VARCHAR(500), meeting_date DATE, imported_by BIGINT, index_status VARCHAR(20), index_failure_reason VARCHAR(255), created_at TIMESTAMP, updated_at TIMESTAMP, UNIQUE(project_id,identity_hash))");
        jdbc.execute("CREATE TABLE IF NOT EXISTS rag_document (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, document_id VARCHAR(128), project_id BIGINT, source_type VARCHAR(30), source_id VARCHAR(500), title VARCHAR(500), content_hash CHAR(64), version INT, status VARCHAR(20), failure_reason VARCHAR(1000), created_at TIMESTAMP, updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS task_draft (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT, created_by BIGINT, source_type VARCHAR(30), source_ref VARCHAR(500), source_content_hash CHAR(64), status VARCHAR(20), idempotency_key VARCHAR(100), failure_reason VARCHAR(1000), submitted_task_ids CLOB, created_at TIMESTAMP, updated_at TIMESTAMP, confirmed_at TIMESTAMP, submitted_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS task_draft_item (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, draft_id BIGINT, title VARCHAR(255), assignee_name VARCHAR(50), description CLOB, priority VARCHAR(20), deadline DATE, sort_order INT, created_at TIMESTAMP, updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS audit_log (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT, user_id BIGINT, action VARCHAR(50), resource_type VARCHAR(50), resource_id BIGINT, request_id VARCHAR(100), detail CLOB, created_at TIMESTAMP)");
        jdbc.update("DELETE FROM audit_log"); jdbc.update("DELETE FROM task_draft_item"); jdbc.update("DELETE FROM task_draft");
        jdbc.update("DELETE FROM rag_document"); jdbc.update("DELETE FROM meeting_record");
        jdbc.update("DELETE FROM project_member"); jdbc.update("DELETE FROM agile_project");
        jdbc.update("INSERT INTO agile_project(id,name,owner_id) VALUES (10,'A',1),(20,'B',1)");
        jdbc.update("INSERT INTO project_member(id,project_id,user_id,role) VALUES (1,10,2,'MEMBER'),(2,10,3,'VIEWER'),(3,20,2,'MEMBER')");
    }

    @AfterEach void clear() { ProjectScope.clear(); }

    @Test
    void memberImportsAndDeduplicatesThenCreatesDraftWithReference() {
        doAnswer(inv -> {
            jdbc.update("INSERT INTO rag_document(document_id,project_id,source_type,source_id,status) VALUES ('doc',?,?,?,'READY')",
                    inv.getArgument(0), inv.getArgument(2), inv.getArgument(3));
            return null;
        }).when(rag).indexDocument(anyLong(), anyString(), anyString(), anyString(), anyString(), isNull(), isNull());
        TaskIssueDTO issue = new TaskIssueDTO(); issue.setTitle("测试任务"); issue.setPriority("HIGH");
        IssueListDTO extracted = new IssueListDTO(); extracted.setIssues(List.of(issue));
        when(agent.extractIssues(anyString())).thenReturn(extracted);
        ProjectScope.authenticate(2L, "meeting-request");
        ProjectScope.runInProject(10L, () -> {
            var request = new MeetingTextRequest("测试会议", "讨论数据库慢查询优化方案", "meeting-a", null, null);
            var first = meetings.importText(10L, request);
            assertEquals("READY", first.indexStatus());
            assertEquals(first.id(), meetings.importText(10L, request).id());
            var draft = meetings.createDraft(10L, first.id());
            assertEquals("MEETING_RECORD", draft.draft().getSourceType());
            assertEquals("meeting-record:" + first.id(), draft.draft().getSourceRef());
            assertEquals("讨论数据库慢查询优化方案", meetings.get(10L, first.id()).content());
            assertThrows(MeetingRecordNotFoundException.class, () -> ProjectScope.runInProject(20L, () -> meetings.get(20L, first.id())));
            verify(rag, times(1)).indexDocument(eq(10L), anyString(), eq("MANUAL_TEXT"), eq("meeting-record:" + first.id()), anyString(), isNull(), isNull());
        });
        assertEquals(3, jdbc.queryForObject("SELECT COUNT(*) FROM audit_log WHERE request_id='meeting-request' AND resource_type='MEETING_RECORD'", Integer.class));
    }

    @Test
    void indexFailurePreservesRecordAndViewerCannotWrite() {
        doThrow(new RuntimeException("secret details")).when(rag).indexDocument(anyLong(), anyString(), anyString(), anyString(), anyString(), isNull(), isNull());
        ProjectScope.runAs(2L, 10L, () -> {
            var result = meetings.importText(10L, new MeetingTextRequest("测试会议", "讨论数据库慢查询优化方案", null, null, null));
            assertEquals("FAILED", result.indexStatus());
            assertEquals("知识库索引失败", meetings.get(10L, result.id()).indexFailureReason());
            ProjectScope.runAs(3L, 10L, () -> {
                assertEquals(result.id(), meetings.get(10L, result.id()).id());
                assertThrows(SecurityException.class, () -> meetings.createDraft(10L, result.id()));
                assertThrows(SecurityException.class, () -> meetings.importText(10L, new MeetingTextRequest("x", "text", null, null, null)));
            });
            ProjectScope.runAs(9L, 10L, () -> assertThrows(SecurityException.class, () -> meetings.get(10L, result.id())));
        });
    }

    @Test
    void memberCanImportAllThreeFileFormatsAndSameFilenameWithNewContentCreatesNewRecord() throws Exception {
        ByteArrayOutputStream output = new ByteArrayOutputStream();
        try (XWPFDocument doc = new XWPFDocument()) {
            doc.createParagraph().createRun().setText("会议行动项目标");
            doc.write(output);
        }
        var txt = new MockMultipartFile("file", "a.txt", "text/plain", "会议内容初始版本".getBytes(StandardCharsets.UTF_8));
        var updated = new MockMultipartFile("file", "a.txt", "text/plain", "会议内容更新版本".getBytes(StandardCharsets.UTF_8));
        var md = new MockMultipartFile("file", "a.md", "text/markdown", "会议行动项目标".getBytes(StandardCharsets.UTF_8));
        var docx = new MockMultipartFile("file", "a.docx", "application/vnd.openxmlformats-officedocument.wordprocessingml.document", output.toByteArray());
        ProjectScope.runAs(2L, 10L, () -> {
            var first = meetings.importFile(10L, txt);
            assertEquals("TXT_FILE", first.sourceType());
            assertEquals(first.id(), meetings.importFile(10L, txt).id());
            assertNotEquals(first.id(), meetings.importFile(10L, updated).id());
            assertEquals("MARKDOWN_FILE", meetings.importFile(10L, md).sourceType());
            assertEquals("DOCX_FILE", meetings.importFile(10L, docx).sourceType());
            assertEquals(4, meetings.list(10L).size());
        });
    }
}
